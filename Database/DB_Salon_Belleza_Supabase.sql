CREATE OR REPLACE FUNCTION actualizar_fecha_producto()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
 NEW.fecha_actualizacion = CURRENT_TIMESTAMP;
 RETURN NEW;
END;
$$;

CREATE TRIGGER trigger_actualizar_fecha_producto
BEFORE UPDATE ON productos
FOR EACH ROW
EXECUTE FUNCTION actualizar_fecha_producto();

CREATE VIEW vw_productos AS
SELECT p.id_producto, p.codigo, p.nombre, c.nombre AS categoria,
       p.descripcion, p.precio, p.stock, p.estado
FROM productos p
JOIN categorias c ON p.id_categoria = c.id_categoria;

CREATE VIEW vw_servicios AS
SELECT id_servicio, nombre, descripcion, precio, duracion, estado
FROM servicios;

CREATE VIEW vw_citas AS
SELECT ci.id_cita, cl.nombre AS cliente, s.nombre AS servicio,
       h.hora, ci.fecha, ci.estado
FROM citas ci
JOIN clientes cl ON ci.id_cliente = cl.id_cliente
JOIN servicios s ON ci.id_servicio = s.id_servicio
JOIN horarios h ON ci.id_horario = h.id_horario;

CREATE VIEW vw_pedidos AS
SELECT p.id_pedido, c.nombre AS cliente, p.metodo_pago,
       p.total, p.estado, p.fecha
FROM pedidos p
JOIN clientes c ON p.id_cliente = c.id_cliente;

CREATE VIEW vw_pagos AS
SELECT pa.id_pago, c.nombre AS cliente, pe.id_pedido, pe.total,
       pa.metodo, pa.estado, pa.comprobante
FROM pagos pa
JOIN pedidos pe ON pa.id_pedido = pe.id_pedido
JOIN clientes c ON pe.id_cliente = c.id_cliente;
